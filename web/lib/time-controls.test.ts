import { test } from "node:test";
import assert from "node:assert/strict";
import {
  TIME_RATES,
  rateToSliderIndex,
  adjacentRate,
  formatRate,
  isLive,
} from "./time-controls.ts";
test("NASA rate map anchors, monotonicity and independent realtime", () => {
  assert.equal(TIME_RATES.length, 101);
  assert.equal(TIME_RATES[0], -94608000);
  assert.equal(TIME_RATES[50], 1);
  assert.equal(TIME_RATES[100], 94608000);
  assert(
    TIME_RATES.every(
      (v, i) =>
        Number.isInteger(v) && v !== 0 && (i === 0 || v >= TIME_RATES[i - 1]),
    ),
  );
  assert.equal(rateToSliderIndex(1), 50);
  assert.equal(adjacentRate(1, -1), -1);
  assert(adjacentRate(1, 1) > 1);
  assert.equal(adjacentRate(TIME_RATES[0], -1), TIME_RATES[0]);
  assert.equal(adjacentRate(TIME_RATES[100], 1), TIME_RATES[100]);
  assert.equal(formatRate(0), "paused");
  assert.equal(formatRate(1), "real rate");
  assert.equal(formatRate(-86400), "-1 day/s");
  assert.throws(() => rateToSliderIndex(NaN));
});
test("LIVE requires playing at 1x within strictly one second", () => {
  assert(isLive(100, 100999, true, 1));
  assert(!isLive(100, 101000, true, 1));
  assert(!isLive(100, 99000, true, 1));
  assert(!isLive(100, 100000, false, 1));
  assert(!isLive(100, 100000, true, -1));
  assert(!isLive(NaN, 100000, true, 1));
});

